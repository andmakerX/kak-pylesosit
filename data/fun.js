// Итог теста по ответам — ключам результатов. Ничья решается в пользу того, кто выпал раньше.
export function quizResult(picks) {
    const score = {};
    let best = null;
    for (const pick of picks) {
        score[pick] = (score[pick] || 0) + 1;
    }
    for (const pick of picks) {
        if (!best || score[pick] > score[best]) {
            best = pick;
        }
    }
    return best ? { key: best, ...QUIZ.results[best] } : null;
}

