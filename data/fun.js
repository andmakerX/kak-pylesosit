export function signById(id) {
    return SIGNS.find(sign => sign.id === id) || null;
}

// Гороскоп знака на день: одна дата и один знак — один и тот же текст у всех.
export function horoscope(signId, iso) {
    const sign = signById(signId);
    if (!sign) {
        return null;
    }
    const random = seededRandom(hashString(`horoscope|${iso}|${signId}`));
    const opener = pickSeeded(OPENERS, random);
    const advice = pickSeeded(ADVICE, random);
    const warning = pickSeeded(WARNINGS, random);
    const item = pickSeeded(LUCKY_ITEMS, random);
    const room = pickSeeded(LUCKY_ROOMS, random);
    const [number, why] = pickSeeded(LUCKY_NUMBERS, random);
    const others = SIGNS.filter(s => s.id !== signId);
    const partner = pickSeeded(others, random);
    const ratings = RATINGS.map(name => ({ name, value: 1 + Math.floor(random() * 5) }));
    return {
        sign,
        text: `${opener} ${advice}`,
        warning: `Остерегайтесь: ${warning}.`,
        lucky: { item, room, number, why },
        partner,
        ratings,
    };
}

